"""Train calibrated category/severity baselines and print measured results.

No scores are bundled. Fit preprocessing and classifiers on train, calibrate
on validation, and evaluate once on existing group-isolated test partitions.
"""

from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import hashlib
from importlib import metadata
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import joblib
import numpy as np
import pandas as pd

from ml.noise import perturb_texts
from ml.normalize import DEFAULT_VARIANTS_PATH
from ml_training.evaluation import evaluate_predictions
from ml_training.experiment_data import load_experiment_data, preprocess_text
from ml_training.modeling import (
    DEFAULT_SENTENCE_MODEL, SentenceEncoder, build_embedding_estimator,
    build_text_estimator, calibrate_prefit,
)

MODEL_NAMES = ("char_svm", "word_lr", "minilm_lr", "minilm_svm")
COHORT_LANGS = {"bangla_test": "bn", "english_test": "en", "banglish_test": "banglish"}


def resolve_path(value: str | Path) -> Path:
    path = Path(value).expanduser()
    return path.resolve() if path.is_absolute() else (ROOT / path).resolve()


def aligned_probabilities(estimator, features, labels: list[str]) -> np.ndarray:
    """Align sklearn's lexical classes to the explicit severity/taxonomy order."""
    raw = estimator.predict_proba(features)
    indices = {str(label): index for index, label in enumerate(estimator.classes_)}
    if set(indices) != set(labels):
        raise ValueError(f"Model classes {sorted(indices)} do not match configured labels {labels}")
    return raw[:, [indices[label] for label in labels]]


def validate_target(data: dict, target: str) -> list[str]:
    labels = data["category_labels" if target == "category" else "severity_labels"]
    if len(labels) < 2:
        raise ValueError(f"{target}: need at least two labels; severity requires --severity-order from least to most severe")
    train = set(data["train"][target])
    val = set(data["val"][target])
    if train != set(labels):
        raise ValueError(f"{target}: every configured class must occur in training. Configured={labels}; training={sorted(train)}")
    if train != val:
        raise ValueError(f"{target}: validation must contain exactly the training classes for calibration. Missing={sorted(train-val)}; unseen={sorted(val-train)}. Correct the upstream group split or collect more validation incidents.")
    return labels


def _related(left: Path, right: Path) -> bool:
    return left == right or left in right.parents or right in left.parents


def validate_destinations(args, input_dir: Path, results: Path, artifacts: Path) -> None:
    if _related(results, artifacts) or _related(input_dir, results) or _related(input_dir, artifacts):
        raise ValueError("Input, results and artifact directories must be separate, non-nested directories")
    if args.natural_test:
        natural = resolve_path(args.natural_test)
        if results == natural or artifacts == natural or results in natural.parents or artifacts in natural.parents:
            raise ValueError("Natural input must be outside output directories")
    for path in (results, artifacts):
        if path.exists() and not path.is_dir():
            raise ValueError(f"Output directory is a file: {path}")
        if path.is_dir() and any(child.name != ".gitkeep" for child in path.iterdir()) and not args.overwrite:
            raise ValueError(f"Output already exists: {path}. Use a fresh run directory or --overwrite.")


def _publish(stage: Path, destination: Path) -> None:
    """Replace only files generated by this run, after all experiments succeed."""
    destination.mkdir(parents=True, exist_ok=True)
    for path in sorted(stage.rglob("*")):
        if path.is_file():
            target = destination / path.relative_to(stage)
            target.parent.mkdir(parents=True, exist_ok=True)
            os.replace(path, target)


def _versions() -> dict:
    result = {"python": sys.version.split()[0]}
    for name in ("pandas", "numpy", "scikit-learn", "matplotlib", "joblib", "sentence-transformers", "torch", "rapidfuzz", "openpyxl", "pyarrow"):
        try:
            result[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            result[name] = None
    return result


def run_experiment(args) -> dict:
    if not 0 <= args.noise_rate <= 1 or args.ece_bins < 2:
        raise ValueError("--noise-rate must be in [0,1] and --ece-bins must be at least 2")
    if len(set(args.models)) != len(args.models) or len(set(args.targets)) != len(args.targets):
        raise ValueError("Do not repeat --models or --targets entries")
    input_dir = resolve_path(args.input_dir)
    results, artifacts = resolve_path(args.results_dir), resolve_path(args.artifacts_dir)
    validate_destinations(args, input_dir, results, artifacts)
    if "severity" in args.targets and not args.severity_order:
        raise ValueError("Provide --severity-order from least to most severe, e.g. low medium high; numeric or alphabetical sorting is not an ordinal scale")
    data = load_experiment_data(input_dir, resolve_path(args.natural_test) if args.natural_test else None, args.severity_order)
    label_sets = {target: validate_target(data, target) for target in args.targets}
    warnings = list(data["warnings"])
    for target in args.targets:
        counts = data["val"].groupby(target)["original_id"].nunique()
        if (counts < 2).any():
            warnings.append(f"{target}: some calibration classes have fewer than two independent incident groups. Treat probability estimates cautiously.")
    cohorts = {name: data["test"].loc[data["test"]["lang"].eq(lang)].copy() for name, lang in COHORT_LANGS.items()}
    cohorts["natural_test"] = data["natural"].copy()
    clean_banglish = cohorts["banglish_test"]
    noisy = clean_banglish.copy()
    noisy_raw = perturb_texts(noisy["raw_text"].tolist(), seed=args.seed, rate=args.noise_rate)
    noisy["text"] = [preprocess_text(text, "banglish") for text in noisy_raw]
    cohorts["banglish_noisy"] = noisy
    if noisy["text"].eq("").any():
        raise ValueError("Noise unexpectedly produced empty cleaned text")

    input_files = [input_dir / f"{split}.csv" for split in ("train", "val", "test")]
    if args.natural_test:
        input_files.append(resolve_path(args.natural_test))
    manifest = {
        "schema_version": 1, "experiment_kind": "calibrated_classifiers",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "seed": args.seed, "models": args.models, "targets": args.targets,
        "labels": label_sets, "versions": _versions(),
        "inputs": [{"path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()} for path in input_files],
        "code_sha256": {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in (
            Path(__file__), ROOT / "ml_training" / "modeling.py", ROOT / "ml_training" / "experiment_data.py",
            ROOT / "ml_training" / "evaluation.py", ROOT / "ml" / "normalize.py", ROOT / "ml" / "noise.py",
        )},
        "normalization_dictionary_sha256": hashlib.sha256(DEFAULT_VARIANTS_PATH.read_bytes()).hexdigest(),
        "calibration": "sigmoid on held-out val using FrozenEstimator; fixed base parameters; no test tuning",
        "decision_rule": "argmax calibrated probability in explicit label order",
        "macro_f1_policy": "fixed target label universe; absent classes contribute zero",
        "noise": {"seed": args.seed, "rate_per_ascii_word": args.noise_rate, "applied_before_same_preprocessing": True},
        "embedding": {"model": args.embedding_model, "requested_revision": args.embedding_revision, "allow_download": args.allow_download} if any(name.startswith("minilm") for name in args.models) else None,
        "data_counts": {split: {"rows": len(data[split]), "groups": int(data[split]["original_id"].nunique())} for split in ("train", "val", "test", "natural")},
        "warnings": warnings, "runs": [],
    }
    encoder = None
    feature_cache: dict[tuple[str, ...], np.ndarray] = {}

    def embeddings(texts: list[str]) -> np.ndarray:
        key = tuple(texts)
        if key not in feature_cache:
            feature_cache[key] = encoder.encode(texts)
        return feature_cache[key]

    # Stage both trees: input/config/optional-dependency failures do not publish
    # a partly evaluated experiment under results/metrics.json.
    results.parent.mkdir(parents=True, exist_ok=True)
    artifacts.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".results-", dir=results.parent) as temporary_results, tempfile.TemporaryDirectory(prefix=".artifacts-", dir=artifacts.parent) as temporary_artifacts:
        result_stage, artifact_stage = Path(temporary_results), Path(temporary_artifacts)
        resources = artifact_stage / "resources"
        resources.mkdir()
        shutil.copyfile(DEFAULT_VARIANTS_PATH, resources / "banglish_variants.json")
        if any(name.startswith("minilm") for name in args.models):
            encoder = SentenceEncoder(args.embedding_model, args.embedding_device, args.allow_download,
                                      args.embedding_batch_size, args.embedding_revision)
            embeddings(data["train"]["text"].tolist())
            encoder.save(artifact_stage / "minilm_encoder")
        table = []
        for target in args.targets:
            labels = label_sets[target]
            for name in args.models:
                embedded = name.startswith("minilm")
                estimator = build_embedding_estimator(name, args.seed) if embedded else build_text_estimator(name, args.seed)
                train_text, val_text = data["train"]["text"].tolist(), data["val"]["text"].tolist()
                train_x, val_x = (embeddings(train_text), embeddings(val_text)) if embedded else (train_text, val_text)
                estimator.fit(train_x, data["train"][target].tolist())
                calibrated = calibrate_prefit(estimator, val_x, data["val"][target].tolist())
                bundle = {
                    "schema_version": 1, "kind": "banglapsg_classifier", "target": target,
                    "model_name": name, "feature_type": "embedding" if embedded else "tfidf",
                    "estimator": calibrated, "labels": labels, "artifact_root_relative": "..",
                    "encoder_dir": "minilm_encoder" if embedded else None,
                    "variants_file": "resources/banglish_variants.json", "versions": manifest["versions"],
                    "normalization_dictionary_sha256": manifest["normalization_dictionary_sha256"],
                    "calibration": manifest["calibration"], "seed": args.seed,
                }
                model_dir = artifact_stage / target
                model_dir.mkdir(exist_ok=True)
                joblib.dump(bundle, model_dir / f"{name}.joblib", compress=3)
                run = {"target": target, "model": name, "artifact": f"{target}/{name}.joblib",
                       "base_estimator": repr(estimator), "cohorts": {}}
                for cohort, full_frame in cohorts.items():
                    frame = full_frame.loc[full_frame[target].ne("")].copy()
                    cohort_dir = Path(target) / name / cohort
                    if len(frame):
                        texts = frame["text"].tolist()
                        features = embeddings(texts) if embedded else texts
                        probabilities = aligned_probabilities(calibrated, features, labels)
                        predictions = np.asarray(labels, dtype=object)[probabilities.argmax(axis=1)].tolist()
                    else:
                        probabilities, predictions = np.empty((0, len(labels))), []
                    metrics = evaluate_predictions(frame[target].tolist(), predictions, probabilities, labels,
                                                   result_stage / cohort_dir, ordinal=target == "severity", n_bins=args.ece_bins)
                    metrics.update(n_total=len(full_frame), n_missing_target=len(full_frame)-len(frame))
                    if frame.empty:
                        metrics["skip_reason"] = "No rows for this cohort" if full_frame.empty else f"No human {target} labels supplied"
                    else:
                        prediction_frame = frame.loc[:, ["id", "original_id", "lang", "text"]].copy()
                        prediction_frame["y_true"], prediction_frame["y_pred"] = frame[target].tolist(), predictions
                        prediction_frame["probabilities"] = [json.dumps(dict(zip(labels, map(float, row))), ensure_ascii=False) for row in probabilities]
                        prediction_frame.to_csv(result_stage / cohort_dir / "predictions.csv", index=False, encoding="utf-8")
                        metrics["files"]["predictions.csv"] = str(result_stage / cohort_dir / "predictions.csv")
                    metrics["files"] = {key: (cohort_dir / Path(path).name).as_posix() for key, path in metrics["files"].items()}
                    if cohort == "banglish_noisy":
                        clean_f1 = run["cohorts"]["banglish_test"]["macro_f1"]
                        noisy_f1 = metrics["macro_f1"]
                        metrics["macro_f1_drop"] = clean_f1 - noisy_f1 if clean_f1 is not None and noisy_f1 is not None else None
                        mask = full_frame[target].ne("").to_numpy()
                        clean_texts = clean_banglish.loc[mask, "text"].tolist()
                        clean_raw = clean_banglish.loc[mask, "raw_text"].tolist()
                        selected_noisy_raw = [text for text, keep in zip(noisy_raw, mask) if keep]
                        metrics["changed_rows_raw"] = sum(a != b for a, b in zip(clean_raw, selected_noisy_raw))
                        metrics["changed_rows_after_preprocessing"] = sum(a != b for a, b in zip(clean_texts, frame["text"]))
                        metrics["noise_rate"] = args.noise_rate
                    run["cohorts"][cohort] = metrics
                    row = {"target": target, "model": name, "cohort": cohort,
                           **{key: value for key, value in metrics.items() if key not in ("files", "labels")}}
                    table.append(row)
                    print(json.dumps({key: row.get(key) for key in ("target", "model", "cohort", "status", "n", "macro_f1", "quadratic_weighted_kappa", "ece", "macro_f1_drop")}, ensure_ascii=False, allow_nan=False), flush=True)
                manifest["runs"].append(run)
        manifest["result_files"] = sorted(path.relative_to(result_stage).as_posix() for path in result_stage.rglob("*") if path.is_file()) + ["metrics.json", "results_table.csv"]
        manifest["artifact_files"] = sorted(path.relative_to(artifact_stage).as_posix() for path in artifact_stage.rglob("*") if path.is_file()) + ["experiment.json"]
        pd.DataFrame(table).to_csv(result_stage / "results_table.csv", index=False, encoding="utf-8")
        rendered = json.dumps(manifest, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
        (result_stage / "metrics.json").write_text(rendered, encoding="utf-8")
        (artifact_stage / "experiment.json").write_text(rendered, encoding="utf-8")
        _publish(artifact_stage, artifacts)
        _publish(result_stage, results)
    for warning in warnings:
        print(f"WARNING: {warning}", file=sys.stderr)
    print(f"Saved measured results: {results / 'metrics.json'}")
    print(f"Saved thesis table: {results / 'results_table.csv'}")
    print(f"Saved joblib models and inference resources: {artifacts}")
    return manifest


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", default="ml_training/data/multilingual")
    parser.add_argument("--natural-test", help="Independent natural CSV; five-field template optionally extended with severity/id/original_id")
    parser.add_argument("--models", nargs="+", choices=MODEL_NAMES, default=list(MODEL_NAMES))
    parser.add_argument("--targets", nargs="+", choices=("category", "severity"), default=["category", "severity"])
    parser.add_argument("--severity-order", nargs="+", help="Exact labels, least to most severe; never inferred")
    parser.add_argument("--results-dir", default="results")
    parser.add_argument("--artifacts-dir", default="artifacts")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--noise-rate", type=float, default=0.15)
    parser.add_argument("--ece-bins", type=int, default=10)
    parser.add_argument("--embedding-model", default=DEFAULT_SENTENCE_MODEL)
    parser.add_argument("--embedding-device", default="cpu")
    parser.add_argument("--embedding-batch-size", type=int, default=64)
    parser.add_argument("--embedding-revision", help="Pin a cached/downloaded model revision for reproducibility")
    parser.add_argument("--allow-download", action="store_true", help="Explicitly allow fetching pretrained encoder weights")
    parser.add_argument("--overwrite", action="store_true", help="Replace this run's generated files; unselected old model/report files remain, so prefer fresh run directories")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        run_experiment(args)
        return 0
    except (ValueError, OSError, RuntimeError, ImportError, csv.Error) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
